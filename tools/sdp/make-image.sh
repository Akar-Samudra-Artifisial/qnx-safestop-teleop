#!/usr/bin/env bash
# Build the QNX 8.0 aarch64le QEMU image with mkqnximage. QNX_IMAGE_CLEAN=1 forces --clean.
# The image autostarts the stack at boot: the binaries (build them first:
# tools/sdp/run.sh make -C qnx) and tools/qemu/teleop-start.sh go to /data, and
# post_startup.sh runs /data/teleop-start.sh (ham -> hamreg simplant -> teleopd, deadline 150).
# Every run forces a rebuild, which resets /data (and the stored token) to the image contents.
# Run INSIDE the container:  ./run.sh /work/tools/sdp/make-image.sh
# Env: TELEOP_TOKEN = pairing token written to /data/teleop.token (kept in
#      build/qnx-image/local/misc_files, git-ignored). Unset: the first boot generates a
#      6-digit token and prints "Pairing token: NNNNNN" on the serial console.
# Output: /work/build/qnx-image/{output,local}  +  project ssh key in .../ssh/
set -euo pipefail

SDP_DIR="${SDP_DIR:-/root/qnx/qnx800}"
OUT_DIR="${QNX_IMAGE_DIR:-/work/build/qnx-image}"
HOSTNAME_QNX="${QNX_HOSTNAME:-safestop}"
KEY="$OUT_DIR/ssh/id_ed25519"
REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

[[ -f "$SDP_DIR/qnxsdp-env.sh" ]] || { echo "Error: SDP not found at $SDP_DIR (run install-qsc.sh)" >&2; exit 1; }
# shellcheck disable=SC1091
source "$SDP_DIR/qnxsdp-env.sh" >/dev/null

# Autostart payload: project binaries + HAM from the SDP (package os_services.ham).
TGT="${QNX_TARGET:-$SDP_DIR/target/qnx}/aarch64le"
BINS=("$REPO_DIR/qnx/teleopd/teleopd" "$REPO_DIR/qnx/simplant/simplant"
      "$REPO_DIR/qnx/teleopctl/teleopctl" "$REPO_DIR/qnx/latbench/latbench"
      "$REPO_DIR/qnx/hamreg/hamreg" "$TGT/usr/sbin/ham" "$TGT/usr/sbin/hamctrl"
      "$REPO_DIR/tools/qemu/teleop-start.sh")
HAM_LIB="$TGT/usr/lib/libham.so.2"
for f in "${BINS[@]}" "$HAM_LIB"; do
  [[ -f "$f" ]] || { echo "Error: $f missing (build: ./run.sh make -C qnx; HAM: install QSC package com.qnx.qnx800.target.os_services.ham)" >&2; exit 1; }
done
TOKEN_SRC="$OUT_DIR/local/misc_files/teleop.token"
if [[ -n "${TELEOP_TOKEN:-}" ]]; then
  [[ "$TELEOP_TOKEN" =~ ^[A-Za-z0-9]{1,32}$ ]] || { echo "Error: TELEOP_TOKEN must be [A-Za-z0-9]{1,32}" >&2; exit 2; }
fi

mkdir -p "$OUT_DIR/ssh" "$OUT_DIR/local/snippets" "$OUT_DIR/local/misc_files"
# Project-only key (never the user's personal key); git-ignored via build/.
[[ -f "$KEY" ]] || ssh-keygen -q -t ed25519 -N '' -C qnx-safestop-teleop -f "$KEY"

# mkqnximage passes the snippets through cpp: no backslashes, no lines starting with "#if" etc.
{
  echo "# local/snippets/data_files.custom (generated by tools/sdp/make-image.sh)"
  for f in "${BINS[@]}"; do echo "[uid=0 gid=0 perms=0755] ${f##*/}=$f"; done
  echo "[uid=0 gid=0 dperms=0755 type=dir] lib"
  echo "[uid=0 gid=0 perms=0644] lib/libham.so.2=$HAM_LIB"
  if [[ -n "${TELEOP_TOKEN:-}" ]]; then
    (umask 077; printf '%s\n' "$TELEOP_TOKEN" > "$TOKEN_SRC")
    echo "[uid=0 gid=0 perms=0600] teleop.token=$TOKEN_SRC"
  else
    rm -f "$TOKEN_SRC"
  fi
} > "$OUT_DIR/local/snippets/data_files.custom"
cat > "$OUT_DIR/local/snippets/post_start.custom" <<'EOF'
# local/snippets/post_start.custom (generated by tools/sdp/make-image.sh)
echo "---> Starting teleop stack (ham, simplant, teleopd)"
if [ -x /data/teleop-start.sh ]; then /data/teleop-start.sh; fi
EOF

clean=()
[[ "${QNX_IMAGE_CLEAN:-0}" == "1" ]] && clean=(--clean)
# mkqnximage only rebuilds when its options change ("Nothing to do" otherwise), not when a
# snippet or a /data payload file changes. Without output/option_files it rebuilds (the same
# path its --clean takes), so /data always gets the current binaries and token.
cd "$OUT_DIR"
# The SDP's cpp sometimes segfaults under amd64 emulation (Apple Silicon), and mkqnximage
# carries on with a truncated generated file (seen: empty data.build, broken root login).
# Detect that (or a non-zero exit) and rebuild, up to 3 attempts. The pipeline sits in an
# "if" so set -e/pipefail do not end the script before the retry.
LOG="$OUT_DIR/mkqnximage.log"
for attempt in 1 2 3; do
  rm -rf "$OUT_DIR/output/option_files"
  if mkqnximage "${clean[@]}" --noprompt --force \
      --type=qemu --arch=aarch64le \
      --hostname="$HOSTNAME_QNX" \
      --ip=dhcp \
      --ssh-ident="$KEY.pub" --sshd-pregen=yes \
      --cpu=2 --ram=1G \
      "$@" 2>&1 | tee "$LOG"; then
    grep -qE "internal compiler error|Segmentation fault" "$LOG" || break
    echo "make-image: cpp crashed during mkqnximage (attempt $attempt), see $LOG" >&2
  else
    echo "make-image: mkqnximage failed (attempt $attempt), see $LOG" >&2
  fi
  [[ $attempt -lt 3 ]] || { echo "Error: mkqnximage failed 3 times" >&2; exit 1; }
done

echo "Image built in $OUT_DIR/output"
ls -l "$OUT_DIR/output"
